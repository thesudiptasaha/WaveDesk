-- Why: Photo Card (a card request that writers fill from a channel template, that a Graphic Designer makes and that is approved and published). Decisions: docs/notes/photocard-notes.md.
-- What it did: three new ticks on team_members (can_request_photo_cards, can_approve_photo_cards, can_manage_photo_templates); new table photo_card_templates with RLS (members read, Owner/Managers and the Manage tick write);
--   16 new columns on contents; guard_contents_insert (a PHOTO CARD can be opened only with the Request tick); guard_contents_update (own exhaustive status rules for PHOTO CARD, stamps of names and times, locked card details after approval);
--   guard_team_members (no self-ticking of the new ticks); team_members_external_rules (external people cannot hold them); notify_content_update (requester credited, designers told on Requested, approvers on In Review).
-- Statuses of a Photo Card: Draft, Requested, Designing, In Review, Ready to Publish (= Approved), Scheduled, Published (+ On Hold, Dropped).
-- Check result after running: 9 rows, all matching the numbers in brackets (3 ticks, 16 columns, 1 table, 4 policies, 1 constraint, 4 patched functions).
begin;

-- 1) three new ticks
alter table public.team_members
  add column if not exists can_request_photo_cards boolean not null default false,
  add column if not exists can_approve_photo_cards boolean not null default false,
  add column if not exists can_manage_photo_templates boolean not null default false;

-- 2) who may manage templates
create or replace function public.i_can_manage_photo_templates()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from team_members
    where auth_user_id = auth.uid() and active
      and (role in ('owner', 'manager') or can_manage_photo_templates)
  );
$$;
revoke all on function public.i_can_manage_photo_templates() from public;
grant execute on function public.i_can_manage_photo_templates() to authenticated;

-- 3) templates table
create table if not exists public.photo_card_templates (
  id bigint generated by default as identity primary key,
  organization_id uuid not null,
  channel text not null,
  number int not null check (number > 0),
  name text not null,
  fields jsonb not null default '[]'::jsonb check (jsonb_typeof(fields) = 'array'),
  sample_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by text,
  unique (organization_id, channel, number)
);
alter table public.photo_card_templates enable row level security;
grant select, insert, update, delete on table public.photo_card_templates to authenticated;

drop policy if exists "photo_card_templates_select" on public.photo_card_templates;
drop policy if exists "photo_card_templates_insert" on public.photo_card_templates;
drop policy if exists "photo_card_templates_update" on public.photo_card_templates;
drop policy if exists "photo_card_templates_delete" on public.photo_card_templates;
create policy "photo_card_templates_select" on public.photo_card_templates for select to authenticated
  using (organization_id = my_org_id() and i_am_active());
create policy "photo_card_templates_insert" on public.photo_card_templates for insert to authenticated
  with check (organization_id = my_org_id() and i_can_manage_photo_templates());
create policy "photo_card_templates_update" on public.photo_card_templates for update to authenticated
  using (organization_id = my_org_id() and i_can_manage_photo_templates())
  with check (organization_id = my_org_id() and i_can_manage_photo_templates());
create policy "photo_card_templates_delete" on public.photo_card_templates for delete to authenticated
  using (organization_id = my_org_id() and i_can_manage_photo_templates());

-- 4) new card columns on contents
alter table public.contents
  add column if not exists template_id bigint references public.photo_card_templates(id) on delete restrict,
  add column if not exists card_fields jsonb not null default '{}'::jsonb,
  add column if not exists is_emergency boolean not null default false,
  add column if not exists card_source text,
  add column if not exists designer_instructions text,
  add column if not exists card_folder text,
  add column if not exists linked_content_uid text,
  add column if not exists requested_by text,
  add column if not exists requested_at timestamptz,
  add column if not exists designer_taken_at timestamptz,
  add column if not exists made_at timestamptz,
  add column if not exists approved_by text,
  add column if not exists approved_at timestamptz,
  add column if not exists review_skipped boolean not null default false,
  add column if not exists correction_count int not null default 0,
  add column if not exists correction_note text;

-- 5) new card opening rule (full replacement, the old function was tiny)
create or replace function public.guard_contents_insert()
returns trigger
language plpgsql security definer
set search_path to 'public'
as $function$
declare
  me public.team_members;
begin
  if auth.uid() is null then
    return new;
  end if;
  if new.status is distinct from 'Draft' or new.published_at is not null then
    raise exception 'New content must start as a Draft';
  end if;
  if new.content_type = 'PHOTO CARD' then
    select * into me from public.my_member_row();
    if not public.perm_of(me, 'can_request_photo_cards') then
      raise exception 'You need the "Request Photo Cards" access';
    end if;
  end if;
  return new;
end;
$function$;

-- 6) patch the other functions and the constraint
create or replace function pg_temp.rep(src text, pat text, repl text) returns text
language plpgsql as $f$
declare n int;
begin
  n := (length(src) - length(replace(src, pat, ''))) / length(pat);
  if n <> 1 then raise exception 'Pattern found % times (need exactly 1): %', n, pat; end if;
  return replace(src, pat, repl);
end $f$;

do $do$
declare def text; d text;
begin
  -- team members: no self-ticking of the new ticks
  select pg_get_functiondef('public.guard_team_members'::regproc) into def;
  def := pg_temp.rep(def, 'new.can_manage_sponsors,', 'new.can_manage_sponsors, new.can_request_photo_cards, new.can_approve_photo_cards, new.can_manage_photo_templates,');
  def := pg_temp.rep(def, 'old.can_manage_sponsors,', 'old.can_manage_sponsors, old.can_request_photo_cards, old.can_approve_photo_cards, old.can_manage_photo_templates,');
  execute def;

  -- external people cannot hold the new ticks
  select pg_get_constraintdef(oid) into d from pg_constraint
   where conname = 'team_members_external_rules' and conrelid = 'public.team_members'::regclass;
  d := pg_temp.rep(d, 'OR can_manage_sponsors)', 'OR can_manage_sponsors OR can_request_photo_cards OR can_approve_photo_cards OR can_manage_photo_templates)');
  execute 'alter table public.team_members drop constraint team_members_external_rules';
  execute 'alter table public.team_members add constraint team_members_external_rules ' || d;

  -- content update rules
  select pg_get_functiondef('public.guard_contents_update'::regproc) into def;

  def := pg_temp.rep(def, 'ok boolean := false;', $q$ok boolean := false;
  pc boolean;
  is_requester boolean;
  is_designer boolean;
  can_approve boolean;$q$);

  def := pg_temp.rep(def, 'pub := mgr or (old.publisher is not null and old.publisher = me.full_name);', $q$pub := mgr or (old.publisher is not null and old.publisher = me.full_name);
  pc := old.content_type = 'PHOTO CARD';
  if pc then
    pub := mgr or coalesce(me.role_publisher, false) or (old.publisher is not null and old.publisher = me.full_name);
  end if;
  is_requester := coalesce(old.requested_by, '') <> '' and old.requested_by = me.full_name;
  is_designer := coalesce(old.graphic_designer, '') <> '' and old.graphic_designer = me.full_name;
  can_approve := mgr or ((public.perm_of(me, 'can_approve_photo_cards') or is_requester) and not is_designer);$q$);

  def := pg_temp.rep(def, 'and not public.perm_of(me, ''can_edit_content_details'') then',
    $q$and not public.perm_of(me, 'can_edit_content_details')
     and not (pc and (public.perm_of(me, 'can_request_photo_cards') or coalesce(me.role_publisher, false))) then$q$);

  def := pg_temp.rep(def, '-- history can only grow', $q$-- photo card details: only requesters (and Managers), locked after approval
  if pc and (new.template_id is distinct from old.template_id
             or new.card_fields is distinct from old.card_fields
             or new.is_emergency is distinct from old.is_emergency
             or new.card_source is distinct from old.card_source
             or new.designer_instructions is distinct from old.designer_instructions) then
    if not public.perm_of(me, 'can_request_photo_cards') then
      raise exception 'You need the "Request Photo Cards" access';
    end if;
    if old.status in ('Ready to Publish', 'Scheduled', 'Published') and not mgr then
      raise exception 'Card details are locked after approval. Ask a Manager';
    end if;
  end if;

  -- history can only grow$q$);

  def := pg_temp.rep(def, '-- workflow: only the real steps, by the right people', $q$-- photo card: names and times are stamped by the database
  if pc and new.status is distinct from old.status then
    if old.status = 'Draft' and new.status = 'Requested' then
      new.requested_by := me.full_name;
      new.requested_at := now();
    elsif old.status = 'Requested' and new.status = 'Designing' then
      if not mgr or coalesce(new.graphic_designer, '') = '' then
        new.graphic_designer := me.full_name;
      end if;
      new.designer_taken_at := now();
    elsif old.status = 'Designing' and new.status = 'Requested' then
      new.graphic_designer := null;
      new.designer_taken_at := null;
    elsif old.status = 'Designing' and new.status = 'In Review' then
      new.made_at := now();
    elsif old.status = 'Designing' and new.status = 'Ready to Publish' then
      new.made_at := now();
      new.review_skipped := true;
    elsif old.status = 'In Review' and new.status = 'Ready to Publish' then
      new.approved_by := me.full_name;
      new.approved_at := now();
    elsif old.status = 'In Review' and new.status = 'Designing' then
      new.correction_count := coalesce(old.correction_count, 0) + 1;
    elsif old.status in ('Ready to Publish', 'Scheduled') and new.status in ('Scheduled', 'Published') then
      if coalesce(new.publisher, '') = '' then
        new.publisher := me.full_name;
      end if;
    end if;
  end if;

  -- workflow: only the real steps, by the right people$q$);

  def := pg_temp.rep(def, 'ok := case', $q$ok := case
      when old.content_type = 'PHOTO CARD' then coalesce((
        case
          when old.status = 'Draft' and new.status = 'Requested'
            then public.perm_of(me, 'can_request_photo_cards') and new.template_id is not null
          when old.status = 'Requested' and new.status = 'Draft'
            then mgr or is_requester
          when old.status = 'Requested' and new.status = 'Designing'
            then mgr or coalesce(me.role_graphic_designer, false)
          when old.status = 'Designing' and new.status = 'Requested'
            then mgr or is_designer
          when old.status = 'Designing' and new.status = 'In Review'
            then mgr or is_designer
          when old.status = 'Designing' and new.status = 'Ready to Publish'
            then coalesce(old.is_emergency, false) and (mgr or is_designer)
          when old.status = 'In Review' and new.status = 'Ready to Publish'
            then can_approve
          when old.status = 'In Review' and new.status = 'Designing'
            then can_approve and btrim(coalesce(new.correction_note, '')) <> ''
          when old.status = 'Ready to Publish' and new.status in ('Scheduled', 'Published')
            then pub
          when old.status = 'Scheduled' and new.status in ('Published', 'Ready to Publish')
            then pub
          when old.status = 'On Hold' and new.status = coalesce(old.previous_status, 'Draft')
            then mgr
          when old.status = 'Dropped' and new.status = 'Draft'
            then mgr
          when old.status not in ('Published', 'Dropped', 'On Hold') and new.status in ('On Hold', 'Dropped')
            then mgr
          else false
        end), false)$q$);
  execute def;

  -- notifications
  select pg_get_functiondef('public.notify_content_update'::regproc) into def;
  def := pg_temp.rep(def, 'new.data_wrangler, new.multimedia_journalist', 'new.data_wrangler, new.multimedia_journalist, new.requested_by');
  def := pg_temp.rep(def, 'or (tm.can_review_videos and new.status = ''Video Review'')', $q$or (tm.can_review_videos and new.status = 'Video Review')
        or (new.content_type = 'PHOTO CARD' and new.status = 'Requested' and coalesce(tm.role_graphic_designer, false))
        or (new.content_type = 'PHOTO CARD' and new.status = 'In Review' and coalesce(tm.can_approve_photo_cards, false))$q$);
  execute def;
end $do$;

commit;

