-- 1) New columns on the templates table (all optional, existing template and the current app keep working)
alter table public.photo_card_templates
  add column if not exists source_package text,
  add column if not exists source_file_name text,
  add column if not exists current_file_name text,
  add column if not exists designed_by text,
  add column if not exists archive_location text,
  add column if not exists version_no int not null default 1,
  add column if not exists updated_by text,
  add column if not exists updated_at timestamptz,
  add column if not exists last_change_note text;

-- 2) Current file name must be unique in the whole organization (ignoring capital letters and outer spaces); empty is allowed
create unique index if not exists photo_card_templates_current_file_name_uq
  on public.photo_card_templates (organization_id, lower(btrim(current_file_name)))
  where current_file_name is not null and btrim(current_file_name) <> '';

-- 3) History table (written only by the trigger, read only by template managers)
create table if not exists public.photo_card_template_history (
  id bigint generated by default as identity primary key,
  organization_id uuid not null,
  template_id bigint not null,
  action text not null check (action in ('created', 'updated', 'deleted')),
  version_no int,
  changed_by text,
  changed_at timestamptz not null default now(),
  note text,
  template_channel text,
  template_number int,
  template_name text,
  changes jsonb not null default '{}'::jsonb
);
create index if not exists photo_card_template_history_tpl_idx
  on public.photo_card_template_history (organization_id, template_id, changed_at desc);

alter table public.photo_card_template_history enable row level security;
revoke all on table public.photo_card_template_history from public, anon, authenticated;
grant select on table public.photo_card_template_history to authenticated;
drop policy if exists "photo_card_template_history_select" on public.photo_card_template_history;
create policy "photo_card_template_history_select" on public.photo_card_template_history
  for select to authenticated
  using (organization_id = my_org_id() and i_can_manage_photo_templates());

-- 4) Trigger function: tidies text, stamps who/when, bumps the version when the file names change,
--    requires a note when file information changes, and writes the history row
create or replace function public.photo_card_template_track()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  who text;
  chg jsonb := '{}'::jsonb;
  note text;
  file_changed boolean := false;
  info_changed boolean := false;
begin
  select tm.full_name into who from public.team_members tm where tm.auth_user_id = auth.uid() limit 1;
  who := coalesce(who, 'SQL / system');

  if tg_op = 'DELETE' then
    insert into public.photo_card_template_history
      (organization_id, template_id, action, version_no, changed_by, template_channel, template_number, template_name, changes)
    values
      (old.organization_id, old.id, 'deleted', old.version_no, who, old.channel, old.number, old.name, '{}'::jsonb);
    return old;
  end if;

  new.source_package := nullif(btrim(new.source_package), '');
  new.source_file_name := nullif(btrim(new.source_file_name), '');
  new.current_file_name := nullif(btrim(new.current_file_name), '');
  new.designed_by := nullif(btrim(new.designed_by), '');
  new.archive_location := nullif(btrim(new.archive_location), '');
  note := nullif(btrim(new.last_change_note), '');
  new.last_change_note := null;

  if tg_op = 'INSERT' then
    new.version_no := 1;
    new.updated_by := who;
    new.updated_at := now();
    insert into public.photo_card_template_history
      (organization_id, template_id, action, version_no, changed_by, note, template_channel, template_number, template_name, changes)
    values
      (new.organization_id, new.id, 'created', 1, who, note, new.channel, new.number, new.name,
       jsonb_strip_nulls(jsonb_build_object(
         'source_package', new.source_package,
         'source_file_name', new.source_file_name,
         'current_file_name', new.current_file_name,
         'designed_by', new.designed_by,
         'archive_location', new.archive_location)));
    return new;
  end if;

  -- UPDATE
  if new.name is distinct from old.name then chg := chg || jsonb_build_object('name', jsonb_build_object('from', old.name, 'to', new.name)); end if;
  if new.channel is distinct from old.channel then chg := chg || jsonb_build_object('channel', jsonb_build_object('from', old.channel, 'to', new.channel)); end if;
  if new.number is distinct from old.number then chg := chg || jsonb_build_object('number', jsonb_build_object('from', old.number, 'to', new.number)); end if;
  if new.active is distinct from old.active then chg := chg || jsonb_build_object('active', jsonb_build_object('from', old.active, 'to', new.active)); end if;
  if new.sample_url is distinct from old.sample_url then chg := chg || jsonb_build_object('sample_url', jsonb_build_object('from', old.sample_url, 'to', new.sample_url)); end if;
  if new.source_package is distinct from old.source_package then chg := chg || jsonb_build_object('source_package', jsonb_build_object('from', old.source_package, 'to', new.source_package)); end if;
  if new.source_file_name is distinct from old.source_file_name then chg := chg || jsonb_build_object('source_file_name', jsonb_build_object('from', old.source_file_name, 'to', new.source_file_name)); end if;
  if new.current_file_name is distinct from old.current_file_name then chg := chg || jsonb_build_object('current_file_name', jsonb_build_object('from', old.current_file_name, 'to', new.current_file_name)); end if;
  if new.designed_by is distinct from old.designed_by then chg := chg || jsonb_build_object('designed_by', jsonb_build_object('from', old.designed_by, 'to', new.designed_by)); end if;
  if new.archive_location is distinct from old.archive_location then chg := chg || jsonb_build_object('archive_location', jsonb_build_object('from', old.archive_location, 'to', new.archive_location)); end if;
  if new.fields is distinct from old.fields then chg := chg || jsonb_build_object('fields', jsonb_build_object('changed', true)); end if;

  file_changed := new.source_package is distinct from old.source_package
               or new.source_file_name is distinct from old.source_file_name
               or new.current_file_name is distinct from old.current_file_name;
  info_changed := file_changed or new.designed_by is distinct from old.designed_by;

  if info_changed and note is null then
    raise exception 'Please write a short note about what changed in the template file information.' using errcode = 'check_violation';
  end if;

  if chg = '{}'::jsonb then
    new.version_no := old.version_no;
    new.updated_by := old.updated_by;
    new.updated_at := old.updated_at;
    return new;
  end if;

  new.version_no := old.version_no + case when file_changed then 1 else 0 end;
  new.updated_by := who;
  new.updated_at := now();

  insert into public.photo_card_template_history
    (organization_id, template_id, action, version_no, changed_by, note, template_channel, template_number, template_name, changes)
  values
    (new.organization_id, new.id, 'updated', new.version_no, who, note, new.channel, new.number, new.name, chg);
  return new;
end;
$fn$;

revoke all on function public.photo_card_template_track() from public;

drop trigger if exists photo_card_template_track_trg on public.photo_card_templates;
create trigger photo_card_template_track_trg
  before insert or update or delete on public.photo_card_templates
  for each row execute function public.photo_card_template_track();

